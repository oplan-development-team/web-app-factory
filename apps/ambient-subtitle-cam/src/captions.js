const lastIndexByBucket = new Map();

/**
 * 指定ムード×トリガー種別からランダムに1件のキャプションを選ぶ。
 * 直前と同じ文言が連続で出ないようにする。
 */
export function pickCaption(mood, trigger) {
  const bank = MOODS[mood]?.[trigger];
  if (!bank || bank.length === 0) return null;
  const key = `${mood}:${trigger}`;
  const lastIndex = lastIndexByBucket.get(key);
  let index = Math.floor(Math.random() * bank.length);
  if (bank.length > 1 && index === lastIndex) {
    index = (index + 1) % bank.length;
  }
  lastIndexByBucket.set(key, index);
  return bank[index];
}

