function toIsoDate(daysAgo: number): string {
  const date = new Date();
  date.setHours(12, 0, 0, 0);
  date.setDate(date.getDate() - daysAgo);
  const year = date.getFullYear();
  const month = `${date.getMonth() + 1}`.padStart(2, '0');
  const day = `${date.getDate()}`.padStart(2, '0');
  return `${year}-${month}-${day}`;
}

export const ARTICLES: readonly Article[] = RAW_ARTICLES.map(({ daysAgo, ...rest }) => ({
  ...rest,
  publishedAt: toIsoDate(daysAgo),
}));

const BY_ID = new Map(ARTICLES.map((article) => [article.id, article]));

export function findArticleById(id: string | undefined): Article | undefined {
  return id ? BY_ID.get(id) : undefined;
}
